#include "libft.h"

t_list	*ft_lstnew(void *content)
{
	t_list	*arr;

	arr = malloc(sizeof(t_list));
	if (!arr)
		return (NULL);
	arr->content = content;
	arr->next = NULL;
	return (arr);
}
